-- Sequence Mail schema for Postgres (schema "sequence"). Generated once from the SQLite schema of
-- src/db.ts; ids and epoch-ms columns are BIGINT, flags stay integers (0/1) as the code expects.

CREATE TABLE accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  oauth_tokens TEXT NOT NULL,
  daily_limit BIGINT NOT NULL,
  sent_today BIGINT NOT NULL DEFAULT 0,
  sent_today_date TEXT,
  last_sent_at BIGINT,
  next_allowed_at BIGINT,
  active BIGINT NOT NULL DEFAULT 1,
  warmup BIGINT NOT NULL DEFAULT 1,
  created_at BIGINT NOT NULL DEFAULT (floor(extract(epoch from now()))::bigint * 1000)
, from_name TEXT, signature TEXT, warmup_started_at BIGINT, owner_ref TEXT);

CREATE TABLE app_settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);

CREATE TABLE campaigns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'paused',
  created_at BIGINT NOT NULL DEFAULT (floor(extract(epoch from now()))::bigint * 1000)
, account_ids TEXT, li_account_ids TEXT, owner_ref TEXT, external_ref TEXT, description TEXT, priority BIGINT NOT NULL DEFAULT 0
, owner_user_id BIGINT GENERATED ALWAYS AS (CASE WHEN owner_ref ~ '^azerit:u:[0-9]+$' THEN substr(owner_ref, 10)::bigint END) STORED
, job_id BIGINT GENERATED ALWAYS AS (CASE WHEN external_ref ~ '^job:[0-9]+$' THEN substr(external_ref, 5)::bigint END) STORED);

CREATE TABLE contacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE,
  first_name TEXT,
  last_name TEXT,
  company TEXT,
  linkedin TEXT,
  extra TEXT,
  do_not_contact BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL DEFAULT (floor(extract(epoch from now()))::bigint * 1000)
, person_id BIGINT);

CREATE TABLE li_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  token_hash TEXT NOT NULL UNIQUE,
  active BIGINT NOT NULL DEFAULT 1,
  warmup BIGINT NOT NULL DEFAULT 1, -- only on bases older than the removal of LinkedIn warm-up
  invites_per_day BIGINT,
  messages_per_day BIGINT,
  warmup_started_at BIGINT,
  next_allowed_at BIGINT,
  paused_until BIGINT,
  last_seen_at BIGINT,
  created_at BIGINT NOT NULL DEFAULT (floor(extract(epoch from now()))::bigint * 1000)
, mode TEXT NOT NULL DEFAULT 'extension', proxy_enc TEXT, session_enc TEXT, session_state TEXT, session_error TEXT, session_updated_at BIGINT, last_inbox_at BIGINT, session_left BIGINT, owner_ref TEXT, serves_dashboard BIGINT NOT NULL DEFAULT 0, member_slug TEXT, member_name TEXT, member_avatar TEXT, member_checked_at BIGINT, connections_at BIGINT, connections_from BIGINT, connections_try_at BIGINT, connections_error TEXT, connections_error_at BIGINT, sent_invitations_at BIGINT);

CREATE TABLE campaign_contacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  contact_id BIGINT NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending',
  current_step BIGINT NOT NULL DEFAULT 0,
  variant TEXT,
  handled_msgs TEXT,
  next_send_at BIGINT,
  account_id BIGINT REFERENCES accounts(id),
  thread_id TEXT,
  last_gmail_message_id TEXT,
  replied_at BIGINT,
  error TEXT, unsub_token TEXT, li_account_id BIGINT REFERENCES li_accounts(id), li_thread_url TEXT, li_reply_text TEXT, inbox_seen_at BIGINT, inbox_done_at BIGINT, vars TEXT, li_accepted BIGINT, li_thread_read TEXT, li_thread TEXT,
  UNIQUE (campaign_id, contact_id)
);

CREATE TABLE li_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_contact_id BIGINT NOT NULL REFERENCES campaign_contacts(id) ON DELETE CASCADE,
  step_number BIGINT NOT NULL,
  linkedin TEXT NOT NULL,
  type TEXT NOT NULL,
  body TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  attempts BIGINT NOT NULL DEFAULT 0,
  error TEXT,
  lease_at BIGINT,
  not_before BIGINT,
  created_at BIGINT NOT NULL DEFAULT (floor(extract(epoch from now()))::bigint * 1000),
  sent_at BIGINT
, li_account_id BIGINT REFERENCES li_accounts(id), member_slug TEXT, ui_failures BIGINT NOT NULL DEFAULT 0, detached BIGINT NOT NULL DEFAULT 0, seen_at BIGINT);

CREATE TABLE li_connections (
  li_account_id BIGINT NOT NULL REFERENCES li_accounts(id) ON DELETE CASCADE,
  slug TEXT NOT NULL,
  connected_on BIGINT,
  seen_at BIGINT NOT NULL,
  PRIMARY KEY (li_account_id, slug)
);

CREATE TABLE li_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL,
  sent_at BIGINT NOT NULL
, li_account_id BIGINT REFERENCES li_accounts(id));

CREATE TABLE li_sent_invitations (
  li_account_id BIGINT NOT NULL REFERENCES li_accounts(id) ON DELETE CASCADE,
  slug TEXT NOT NULL,
  sent_at BIGINT,
  seen_at BIGINT NOT NULL,
  PRIMARY KEY (li_account_id, slug)
);

CREATE TABLE li_token_aliases (token_hash TEXT PRIMARY KEY, li_account_id BIGINT NOT NULL REFERENCES li_accounts(id));

CREATE TABLE messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_contact_id BIGINT NOT NULL REFERENCES campaign_contacts(id) ON DELETE CASCADE,
  account_id BIGINT NOT NULL REFERENCES accounts(id),
  step_number BIGINT NOT NULL,
  gmail_message_id TEXT,
  gmail_thread_id TEXT,
  sent_at BIGINT NOT NULL DEFAULT (floor(extract(epoch from now()))::bigint * 1000)
);

CREATE TABLE enrollment_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL,
  owner_ref TEXT,
  external_ref TEXT,
  contact_id BIGINT,
  person_id BIGINT,
  status TEXT,
  invited_at BIGINT,
  messaged_at BIGINT,
  emailed_at BIGINT,
  replied_at BIGINT,
  removed_at BIGINT NOT NULL
);

CREATE TABLE owner_opt_outs (
  owner_ref TEXT NOT NULL,
  contact_id BIGINT NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  reason TEXT,
  created_at BIGINT NOT NULL DEFAULT (floor(extract(epoch from now()))::bigint * 1000),
  PRIMARY KEY (owner_ref, contact_id)
);

CREATE TABLE steps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  step_number BIGINT NOT NULL,
  subject TEXT NOT NULL,
  subject_b TEXT,
  body TEXT NOT NULL,
  wait_days BIGINT NOT NULL DEFAULT 0,
  channel TEXT NOT NULL DEFAULT 'email',
  li_action TEXT, branch TEXT, with_previous BIGINT NOT NULL DEFAULT 0,
  UNIQUE (campaign_id, step_number)
);

CREATE TABLE variable_instructions (name TEXT PRIMARY KEY, instruction TEXT NOT NULL);

