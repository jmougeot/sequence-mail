CREATE INDEX idx_contacts_linkedin ON contacts (linkedin);
CREATE INDEX idx_li_accounts_owner ON li_accounts (owner_ref);
CREATE INDEX idx_li_actions_account ON li_actions (li_account_id, status);
CREATE INDEX idx_li_actions_cc ON li_actions (campaign_contact_id);
CREATE INDEX idx_li_actions_status ON li_actions (status);
CREATE INDEX idx_li_log_account ON li_log (li_account_id, sent_at);
