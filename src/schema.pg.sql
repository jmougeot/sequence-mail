-- SQLite functions the statements rely on, same names, same results.
CREATE FUNCTION max(a bigint, b bigint) RETURNS bigint LANGUAGE sql IMMUTABLE STRICT
  AS 'SELECT CASE WHEN a > b THEN a ELSE b END';

-- RFC 7396 merge patch on JSON kept as text, like SQLite's json_patch
CREATE FUNCTION json_merge(target jsonb, patch jsonb) RETURNS jsonb LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
  k text;
  v jsonb;
  out jsonb := CASE WHEN jsonb_typeof(target) = 'object' THEN target ELSE '{}'::jsonb END;
BEGIN
  IF jsonb_typeof(patch) <> 'object' THEN RETURN patch; END IF;
  FOR k, v IN SELECT * FROM jsonb_each(patch) LOOP
    IF jsonb_typeof(v) = 'null' THEN out := out - k;
    ELSE out := jsonb_set(out, ARRAY[k], json_merge(COALESCE(out -> k, 'null'::jsonb), v));
    END IF;
  END LOOP;
  RETURN out;
END $$;

CREATE FUNCTION json_patch(target text, patch text) RETURNS text LANGUAGE sql IMMUTABLE STRICT
  AS 'SELECT json_merge(target::jsonb, patch::jsonb)::text';

CREATE FUNCTION json_extract(doc text, path text) RETURNS text LANGUAGE sql IMMUTABLE STRICT
  AS $$SELECT doc::jsonb #>> string_to_array(substr(path, 3), '.')$$;

CREATE FUNCTION json_each(doc text) RETURNS TABLE (value text) LANGUAGE sql IMMUTABLE STRICT
  AS 'SELECT jsonb_array_elements_text(doc::jsonb)';
