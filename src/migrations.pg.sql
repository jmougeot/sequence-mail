-- Changes to the "sequence" schema made after the switchover to Postgres (31 Oct 2026).
-- schema.pg.sql only builds a fresh copy in shadow mode; in DB_MODE=postgres nothing recreates
-- the schema, so every change goes here too, idempotent: applied at each start (src/db.ts).

-- Memory of deleted enrollments (services/history.ts), 5 Nov 2026
CREATE TABLE IF NOT EXISTS enrollment_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL,
  owner_ref TEXT,
  external_ref TEXT,
  contact_id BIGINT,
  external_key TEXT,
  status TEXT,
  invited_at BIGINT,
  messaged_at BIGINT,
  emailed_at BIGINT,
  replied_at BIGINT,
  removed_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_enrollment_history_key ON enrollment_history (owner_ref, external_key);
