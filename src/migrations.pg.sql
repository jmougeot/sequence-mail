-- Azerit candidates: one identity, in Azerit's people table (ADR of 5 Nov 2026). A contact with a
-- person_id reads its name, email, company and LinkedIn there; every read of a contact's identity
-- goes through contacts_v. Without public.people (or without the right to read it) the view is the
-- table itself. Same columns, same order in both versions. A person's LinkedIn is her LinkedIn
-- account in public.accounts (Azerit's ADR step 6, 6 Nov 2026: one row per account, pointing to
-- its person), before that people.linkedin_key. Azerit's migration writes the same view and
-- function when it moves to accounts (db/_migrations.py, _sequence_reads_accounts). A person's
-- company is her employer (people.company_id -> public.companies) or, failing that, her situation as
-- written (people.employment_note: Freelance, a company the referential does not know…) once
-- people.current_company is gone (ids everywhere, Nov 2026), before that people.current_company;
-- without the right to read companies, only the note counts and a contact whose person has an
-- employer keeps its own company column.
ALTER TABLE contacts ADD COLUMN IF NOT EXISTS person_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_contacts_person ON contacts (person_id);
DO $$
DECLARE
  li TEXT := 'p.linkedin_key';
  co TEXT := 'COALESCE(NULLIF(p.current_company, ''''), c.company)'; -- the contact's company, as text
  co_join TEXT := '';                                                -- what co reads besides people
  has_co TEXT := 'NULLIF(p.current_company, '''') IS NOT NULL';       -- the person holds a company
BEGIN
  IF to_regclass('public.accounts') IS NOT NULL AND has_table_privilege('public.accounts', 'SELECT') THEN
    li := '(SELECT a.handle FROM public.accounts a WHERE a.person_id = p.id AND a.platform = ''linkedin'' '
          'AND a.deleted_at IS NULL ORDER BY a.id DESC LIMIT 1)';
  END IF;
  IF to_regclass('public.people') IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM pg_attribute WHERE attrelid = to_regclass('public.people')
         AND attname = 'current_company' AND NOT attisdropped) THEN
    IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = to_regclass('public.people')
                     AND attname = 'employment_note' AND NOT attisdropped) THEN
      co := 'c.company';
      has_co := 'FALSE';
    ELSIF to_regclass('public.companies') IS NOT NULL AND has_table_privilege('public.companies', 'SELECT') THEN
      -- same text as Azerit's migration (db/_migrations.py, _sequence_reads_accounts)
      co := 'COALESCE(NULLIF(co.name, ''''), NULLIF(p.employment_note, ''''), c.company)';
      co_join := 'LEFT JOIN public.companies co ON co.id = p.company_id';
      has_co := '(p.company_id IS NOT NULL OR NULLIF(p.employment_note, '''') IS NOT NULL)';
    ELSE
      co := 'COALESCE(NULLIF(p.employment_note, ''''), c.company)';
      has_co := 'NULLIF(p.employment_note, '''') IS NOT NULL';
    END IF;
  END IF;
  IF to_regclass('public.people') IS NOT NULL AND has_table_privilege('public.people', 'SELECT') THEN
    EXECUTE format($view$
      CREATE OR REPLACE VIEW contacts_v AS
      SELECT c.id,
             COALESCE(NULLIF(p.email, ''), c.email)::text AS email,
             COALESCE(NULLIF(p.first_name, ''), c.first_name)::text AS first_name,
             COALESCE(NULLIF(p.last_name, ''), c.last_name)::text AS last_name,
             %2$s::text AS company,
             COALESCE('https://www.linkedin.com/in/' || %1$s, c.linkedin)::text AS linkedin,
             c.extra, c.do_not_contact, c.created_at, c.person_id
      FROM contacts c LEFT JOIN public.people p ON p.id = c.person_id
      %3$s
    $view$, li, co, co_join);
  ELSE
    EXECUTE 'CREATE OR REPLACE VIEW contacts_v AS SELECT * FROM contacts';
  END IF;
  -- Contacts enrolled before people existed: their person through the lead key of their enrollment
  -- (public.lead_people). Enrollments made since carry the person (services/service-routes.ts).
  IF to_regclass('public.lead_people') IS NOT NULL AND has_table_privilege('public.lead_people', 'SELECT') THEN
    UPDATE contacts c SET person_id = m.person_id
    FROM (SELECT cc.contact_id, MIN(lp.person_id) AS person_id
          FROM campaign_contacts cc
          JOIN campaigns ca ON ca.id = cc.campaign_id
          JOIN public.lead_people lp ON lp.lead_key = cc.external_key
          WHERE ca.owner_ref LIKE 'azerit:u:%'
          GROUP BY cc.contact_id HAVING COUNT(DISTINCT lp.person_id) = 1) m
    WHERE c.id = m.contact_id AND c.person_id IS NULL;
  END IF;
  -- A contact tied to a person keeps none of what the person holds: forget_copied_identity() clears
  -- those columns (run here, and after each import or enrollment, see db.ts). Without people, it
  -- does nothing.
  IF to_regclass('public.people') IS NOT NULL AND has_table_privilege('public.people', 'SELECT') THEN
    EXECUTE format($fn$
      CREATE OR REPLACE FUNCTION forget_copied_identity() RETURNS BIGINT LANGUAGE sql
      SET search_path FROM CURRENT AS $body$
        WITH done AS (
          UPDATE contacts c SET
            email      = CASE WHEN NULLIF(p.email, '') IS NOT NULL THEN NULL ELSE c.email END,
            first_name = CASE WHEN NULLIF(p.first_name, '') IS NOT NULL THEN NULL ELSE c.first_name END,
            last_name  = CASE WHEN NULLIF(p.last_name, '') IS NOT NULL THEN NULL ELSE c.last_name END,
            company    = CASE WHEN %2$s THEN NULL ELSE c.company END,
            linkedin   = CASE WHEN %1$s IS NOT NULL THEN NULL ELSE c.linkedin END
          FROM public.people p
          WHERE p.id = c.person_id
            AND ((c.email IS NOT NULL AND NULLIF(p.email, '') IS NOT NULL)
              OR (c.first_name IS NOT NULL AND NULLIF(p.first_name, '') IS NOT NULL)
              OR (c.last_name IS NOT NULL AND NULLIF(p.last_name, '') IS NOT NULL)
              OR (c.company IS NOT NULL AND %2$s)
              OR (c.linkedin IS NOT NULL AND %1$s IS NOT NULL))
          RETURNING 1)
        SELECT COUNT(*) FROM done
      $body$
    $fn$, li, has_co);
  ELSE
    EXECUTE 'CREATE OR REPLACE FUNCTION forget_copied_identity() RETURNS BIGINT LANGUAGE sql AS $b$ SELECT 0::bigint $b$';
  END IF;
  PERFORM forget_copied_identity();
  -- person_id is a real foreign key to Azerit's people (granted by Azerit's migrations): a person
  -- still named by a contact cannot be deleted (Azerit's merge() moves the contacts first). An
  -- orphan left by an older version only warns, so a start is never blocked.
  IF to_regclass('public.people') IS NOT NULL AND has_table_privilege('public.people', 'REFERENCES')
     AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'contacts_person_fk'
                     AND conrelid = 'contacts'::regclass) THEN
    BEGIN
      ALTER TABLE contacts ADD CONSTRAINT contacts_person_fk
        FOREIGN KEY (person_id) REFERENCES public.people (id);
    EXCEPTION WHEN foreign_key_violation THEN
      RAISE WARNING 'contacts_person_fk not added: % contact(s) name a missing person',
        (SELECT COUNT(*) FROM contacts c WHERE c.person_id IS NOT NULL
           AND NOT EXISTS (SELECT 1 FROM public.people p WHERE p.id = c.person_id));
    END;
  END IF;
END $$;

-- The Azerit person an enrollment was made for (public.people.id), 7 Nov 2026: how Azerit names its
-- candidates since then, rather than the key of its lead, which changed when a GitHub was set on a
-- candidate. Set only by the service routes (/hold, /enroll) from the person Azerit sends, whatever
-- contact the import kept (a shared email or LinkedIn can land on another person's contact); NULL
-- outside Azerit (prospection, dashboard, MCP), so Azerit never reads those. The history keeps it
-- too (services/history.ts).
-- The lead key (external_key) stays, still written when Azerit sends it, so that the previous
-- Azerit keeps working against this version and the previous Sequence Mail restarts on this base.
-- Dropping it (and idx_enrollment_history_key) belongs to a later deployment, once Azerit no
-- longer sends keys.
-- Enrollments and history lines made with a key and no person (before this version, or by the
-- previous Azerit) take the person their key gives in public.lead_people when it gives exactly
-- one, else the person of their contact; every start, so the stragglers of the previous Azerit
-- follow. Counted in NOTICEs. Runs before Azerit's own migration (lead_people still there); without
-- lead_people (or the right to read it), the contact alone decides, which is said too.
ALTER TABLE campaign_contacts ADD COLUMN IF NOT EXISTS external_key TEXT;
ALTER TABLE campaign_contacts ADD COLUMN IF NOT EXISTS person_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_cc_person ON campaign_contacts (campaign_id, person_id);
ALTER TABLE enrollment_history ADD COLUMN IF NOT EXISTS person_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_enrollment_history_person ON enrollment_history (owner_ref, person_id);
DO $$
DECLARE
  -- each lead key with its person and how many people it gives (only 1 is trusted)
  keys TEXT := '(SELECT NULL::text AS lead_key, NULL::bigint AS person_id, 0::bigint AS people WHERE FALSE)';
  active CONSTANT TEXT := $a$('held', 'pending', 'in_progress', 'awaiting_li')$a$;
  t TEXT;
  by_key BIGINT; by_contact BIGINT; disagree BIGINT; ambiguous BIGINT; left_active BIGINT; left_other BIGINT; n BIGINT;
BEGIN
  IF to_regclass('public.lead_people') IS NOT NULL AND has_table_privilege('public.lead_people', 'SELECT') THEN
    keys := '(SELECT lead_key::text AS lead_key, MIN(person_id)::bigint AS person_id, COUNT(DISTINCT person_id) AS people '
            'FROM public.lead_people GROUP BY lead_key)';
  ELSIF EXISTS (SELECT 1 FROM campaign_contacts WHERE external_key IS NOT NULL AND person_id IS NULL)
     OR EXISTS (SELECT 1 FROM enrollment_history WHERE external_key IS NOT NULL AND person_id IS NULL) THEN
    RAISE NOTICE 'person_id: public.lead_people unreadable, lines with a key and no person take their contact''s person';
  END IF;
  FOREACH t IN ARRAY ARRAY['campaign_contacts', 'enrollment_history'] LOOP
    EXECUTE format($q$
      SELECT COUNT(*) FILTER (WHERE k.people = 1),
             COUNT(*) FILTER (WHERE k.people IS DISTINCT FROM 1 AND c.person_id IS NOT NULL),
             COUNT(*) FILTER (WHERE k.people = 1 AND c.person_id IS NOT NULL AND c.person_id <> k.person_id),
             COUNT(*) FILTER (WHERE k.people > 1),
             COUNT(*) FILTER (WHERE k.people IS DISTINCT FROM 1 AND c.person_id IS NULL AND x.status IN %3$s),
             COUNT(*) FILTER (WHERE k.people IS DISTINCT FROM 1 AND c.person_id IS NULL AND COALESCE(x.status, '') NOT IN %3$s)
      FROM %1$I x LEFT JOIN contacts c ON c.id = x.contact_id LEFT JOIN %2$s k ON k.lead_key = x.external_key
      WHERE x.external_key IS NOT NULL AND x.person_id IS NULL
    $q$, t, keys, active) INTO by_key, by_contact, disagree, ambiguous, left_active, left_other;
    IF by_key + by_contact + left_active + left_other = 0 THEN CONTINUE; END IF;
    EXECUTE format($q$
      UPDATE %1$I x SET person_id = r.person_id
      FROM (SELECT y.id, COALESCE(CASE WHEN k.people = 1 THEN k.person_id END, c.person_id) AS person_id
            FROM %1$I y LEFT JOIN contacts c ON c.id = y.contact_id LEFT JOIN %2$s k ON k.lead_key = y.external_key
            WHERE y.external_key IS NOT NULL AND y.person_id IS NULL) r
      WHERE x.id = r.id AND r.person_id IS NOT NULL
    $q$, t, keys);
    RAISE NOTICE '%.person_id: % by lead key, % by contact (key and contact disagree on %: key kept; % key(s) giving several people), unresolved: % active (held, pending, in_progress, awaiting_li), % other',
      t, by_key, by_contact, disagree, ambiguous, left_active, left_other;
  END LOOP;
  -- A person enrolled twice in one campaign (two keys or two contacts before this version): the
  -- routes launch only one of them (services/service-routes.ts), said here so it can be cleaned.
  SELECT COUNT(*) INTO n FROM (SELECT 1 FROM campaign_contacts WHERE person_id IS NOT NULL
                               GROUP BY campaign_id, person_id HAVING COUNT(*) > 1) d;
  IF n > 0 THEN
    RAISE NOTICE 'campaign_contacts: % (campaign, person) pair(s) with several enrollments', n;
  END IF;
END $$;

-- Azerit owner and job of a campaign, as real columns for joins with public.users / public.jobs
-- (ADR of 5 Nov 2026). Generated from owner_ref / external_ref, so they cannot diverge. No foreign
-- key: a campaign outlives its job (it is the record of what was sent).
ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS owner_user_id BIGINT
  GENERATED ALWAYS AS (CASE WHEN owner_ref ~ '^azerit:u:[0-9]+$' THEN substr(owner_ref, 10)::bigint END) STORED;
ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS job_id BIGINT
  GENERATED ALWAYS AS (CASE WHEN external_ref ~ '^job:[0-9]+$' THEN substr(external_ref, 5)::bigint END) STORED;
CREATE INDEX IF NOT EXISTS idx_campaigns_job ON campaigns (job_id);

