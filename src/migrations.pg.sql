-- Changes to the "sequence" schema made after the switchover to Postgres (31 Oct 2026).
-- schema.pg.sql only builds a fresh copy in shadow mode; in DB_MODE=postgres nothing recreates
-- the schema, so every change goes here too, idempotent: applied at each start (src/db.ts).

-- Memory of deleted enrollments (services/history.ts), 5 Nov 2026
CREATE TABLE IF NOT EXISTS enrollment_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL,
  owner_ref TEXT,
  external_ref TEXT,
  contact_id BIGINT,
  external_key TEXT,
  status TEXT,
  invited_at BIGINT,
  messaged_at BIGINT,
  emailed_at BIGINT,
  replied_at BIGINT,
  removed_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_enrollment_history_key ON enrollment_history (owner_ref, external_key);

-- Azerit candidates: one identity, in Azerit's people table (ADR of 5 Nov 2026). A contact with a
-- person_id reads its name, email, company and LinkedIn there; every read of a contact's identity
-- goes through contacts_v. Without public.people (or without the right to read it) the view is the
-- table itself. Same columns, same order in both versions.
ALTER TABLE contacts ADD COLUMN IF NOT EXISTS person_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_contacts_person ON contacts (person_id);
DO $$
BEGIN
  IF to_regclass('public.people') IS NOT NULL AND has_table_privilege('public.people', 'SELECT') THEN
    EXECUTE $view$
      CREATE OR REPLACE VIEW contacts_v AS
      SELECT c.id,
             COALESCE(NULLIF(p.email, ''), c.email)::text AS email,
             COALESCE(NULLIF(p.first_name, ''), c.first_name)::text AS first_name,
             COALESCE(NULLIF(p.last_name, ''), c.last_name)::text AS last_name,
             COALESCE(NULLIF(p.current_company, ''), c.company)::text AS company,
             COALESCE('https://www.linkedin.com/in/' || p.linkedin_key, c.linkedin)::text AS linkedin,
             c.extra, c.do_not_contact, c.created_at, c.person_id
      FROM contacts c LEFT JOIN public.people p ON p.id = c.person_id
    $view$;
  ELSE
    EXECUTE 'CREATE OR REPLACE VIEW contacts_v AS SELECT * FROM contacts';
  END IF;
  -- Contacts enrolled before people existed: their person through the lead key of their enrollment
  -- (public.lead_people). Enrollments made since carry the person (services/service-routes.ts).
  IF to_regclass('public.lead_people') IS NOT NULL AND has_table_privilege('public.lead_people', 'SELECT') THEN
    UPDATE contacts c SET person_id = m.person_id
    FROM (SELECT cc.contact_id, MIN(lp.person_id) AS person_id
          FROM campaign_contacts cc
          JOIN campaigns ca ON ca.id = cc.campaign_id
          JOIN public.lead_people lp ON lp.lead_key = cc.external_key
          WHERE ca.owner_ref LIKE 'azerit:u:%'
          GROUP BY cc.contact_id HAVING COUNT(DISTINCT lp.person_id) = 1) m
    WHERE c.id = m.contact_id AND c.person_id IS NULL;
  END IF;
  -- A contact tied to a person keeps none of what the person holds: forget_copied_identity() clears
  -- those columns (run here, and after each import or enrollment, see db.ts). Without people, it
  -- does nothing.
  IF to_regclass('public.people') IS NOT NULL AND has_table_privilege('public.people', 'SELECT') THEN
    EXECUTE $fn$
      CREATE OR REPLACE FUNCTION forget_copied_identity() RETURNS BIGINT LANGUAGE sql
      SET search_path FROM CURRENT AS $body$
        WITH done AS (
          UPDATE contacts c SET
            email      = CASE WHEN NULLIF(p.email, '') IS NOT NULL THEN NULL ELSE c.email END,
            first_name = CASE WHEN NULLIF(p.first_name, '') IS NOT NULL THEN NULL ELSE c.first_name END,
            last_name  = CASE WHEN NULLIF(p.last_name, '') IS NOT NULL THEN NULL ELSE c.last_name END,
            company    = CASE WHEN NULLIF(p.current_company, '') IS NOT NULL THEN NULL ELSE c.company END,
            linkedin   = CASE WHEN p.linkedin_key IS NOT NULL THEN NULL ELSE c.linkedin END
          FROM public.people p
          WHERE p.id = c.person_id
            AND ((c.email IS NOT NULL AND NULLIF(p.email, '') IS NOT NULL)
              OR (c.first_name IS NOT NULL AND NULLIF(p.first_name, '') IS NOT NULL)
              OR (c.last_name IS NOT NULL AND NULLIF(p.last_name, '') IS NOT NULL)
              OR (c.company IS NOT NULL AND NULLIF(p.current_company, '') IS NOT NULL)
              OR (c.linkedin IS NOT NULL AND p.linkedin_key IS NOT NULL))
          RETURNING 1)
        SELECT COUNT(*) FROM done
      $body$
    $fn$;
  ELSE
    EXECUTE 'CREATE OR REPLACE FUNCTION forget_copied_identity() RETURNS BIGINT LANGUAGE sql AS $b$ SELECT 0::bigint $b$';
  END IF;
  PERFORM forget_copied_identity();
  -- person_id is a real foreign key to Azerit's people (granted by Azerit's migrations): a person
  -- still named by a contact cannot be deleted (Azerit's merge() moves the contacts first). An
  -- orphan left by an older version only warns, so a start is never blocked.
  IF to_regclass('public.people') IS NOT NULL AND has_table_privilege('public.people', 'REFERENCES')
     AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'contacts_person_fk'
                     AND conrelid = 'contacts'::regclass) THEN
    BEGIN
      ALTER TABLE contacts ADD CONSTRAINT contacts_person_fk
        FOREIGN KEY (person_id) REFERENCES public.people (id);
    EXCEPTION WHEN foreign_key_violation THEN
      RAISE WARNING 'contacts_person_fk not added: % contact(s) name a missing person',
        (SELECT COUNT(*) FROM contacts c WHERE c.person_id IS NOT NULL
           AND NOT EXISTS (SELECT 1 FROM public.people p WHERE p.id = c.person_id));
    END;
  END IF;
END $$;

-- Azerit owner and job of a campaign, as real columns for joins with public.users / public.jobs
-- (ADR of 5 Nov 2026). Generated from owner_ref / external_ref, so they cannot diverge. No foreign
-- key: a campaign outlives its job (it is the record of what was sent).
ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS owner_user_id BIGINT
  GENERATED ALWAYS AS (CASE WHEN owner_ref ~ '^azerit:u:[0-9]+$' THEN substr(owner_ref, 10)::bigint END) STORED;
ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS job_id BIGINT
  GENERATED ALWAYS AS (CASE WHEN external_ref ~ '^job:[0-9]+$' THEN substr(external_ref, 5)::bigint END) STORED;
CREATE INDEX IF NOT EXISTS idx_campaigns_job ON campaigns (job_id);
